#include "road_mesh.hpp"
#include "road.hpp"

#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <stdexcept>

// Regenerate after changing road geometry (UV/texture edits do not need this).
// Profiles are CPU-only, so placement never has to load models or access a GPU.
int main(int argc, char** argv)
{
    try
    {
        if (argc != 3) throw std::runtime_error("Usage: CityGenerateRoadCollision assets-directory output-header");
        // Load everything before touching the output file.
        std::array<StaticMesh, RoadAssets.size()> meshes;
        for (std::size_t i = 0; i < meshes.size(); ++i)
            meshes[i] = LoadRoadMesh(std::filesystem::path(argv[1]) / RoadAssets[i].model, RoadAssets[i]);
        std::ofstream out(argv[2]);
        if (!out) throw std::runtime_error("Cannot create collision header");
        out << "// Generated by tools/generate_road_collision.cpp from the fitted road GLBs.\n"
               "// Triangle positions in tile units, before the instance rotation/stretch.\n"
               "#pragma once\n#include <array>\n#include <span>\n\n"
               "struct RoadCollisionPoint { double x, z; };\n\n";
        out << std::fixed << std::setprecision(9);
        std::size_t maximum = 0;
        for (std::size_t i = 0; i < meshes.size(); ++i)
        {
            const auto& mesh = meshes[i];
            maximum = std::max(maximum, mesh.indices.size());
            out << "// " << RoadAssets[i].model << '\n';
            out << "inline constexpr std::array<RoadCollisionPoint, " << mesh.indices.size()
                << "> RoadCollisionShape" << i << "{{\n";
            for (auto index : mesh.indices)
            {
                const auto& v = mesh.vertices[index];
                out << "    {" << v.x << ", " << v.z << "},\n";
            }
            out << "}};\n\n";
        }
        out << "inline constexpr std::size_t RoadCollisionMaxPoints = " << maximum << ";\n";
        out << "inline constexpr std::array<std::span<const RoadCollisionPoint>, " << meshes.size()
            << "> RoadCollisionShapes{{\n";
        for (std::size_t i = 0; i < meshes.size(); ++i) out << "    RoadCollisionShape" << i << ",\n";
        out << "}};\n";
        if (!out) throw std::runtime_error("Failed to write collision header");
        return 0;
    }
    catch (const std::exception& e) { std::cerr << e.what() << '\n'; return 1; }
}
